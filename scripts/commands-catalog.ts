import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { ModuleRegistry, auditBudget } from "@keystone/kernel";
import { modules } from "../apps/bot/src/modules";

/**
 * Generate the command catalog from the live registry.
 *
 * This is deliberately not a hand-maintained list: `/help`, the README and the
 * vault page all describe the same registry Discord receives, so a command
 * cannot exist in only one place.
 */
const root = process.cwd();
const registry = new ModuleRegistry().registerAll(modules);
const report = auditBudget(registry);
const catalog = registry.catalog();
const updatedAt = new Date().toISOString().slice(0, 10);

const data = {
  schemaVersion: 1,
  updatedAt,
  source: "packages/kernel ModuleRegistry catalog()",
  roots: report.commands,
  subcommands: report.subcommands,
  actions: report.actions,
  limit: report.limit,
  commands: catalog.map((entry) => ({
    name: entry.name,
    moduleId: entry.moduleId,
    description: entry.description,
    options: entry.options.map((option) => option.name),
    subcommands: entry.subcommands.map((subcommand) => ({
      name: subcommand.name,
      description: subcommand.description,
      ...(subcommand.group ? { group: subcommand.group } : {}),
      options: subcommand.options.map((option) => option.name),
    })),
  })),
};

const markdown = [
  "<!-- generated by pnpm commands:catalog; do not edit by hand -->",
  "",
  "# Command catalog",
  "",
  "> Generated from the live `ModuleRegistry`. This is the list Discord receives.",
  "> Run `pnpm commands:catalog` after changing a command definition.",
  "",
  `**${report.commands} roots · ${report.subcommands} subcommands · ${report.actions} total actions · ${report.commands}/${report.limit} global roots used.**`,
  "",
  "A root is one of Discord's 100 global chat-input commands. Subcommands live",
  "inside that root and do not spend another slot. Type `/` in Discord, choose a",
  "root, then choose a subcommand.",
  "",
  "| Root | Module | Subcommands |",
  "| --- | --- | ---: |",
  ...catalog.map(
    (entry) => `| \`/${entry.name}\` | \`${entry.moduleId}\` | ${entry.subcommands.length} |`,
  ),
  "",
  ...catalog.flatMap((entry) => [
    `## \`/${entry.name}\``,
    "",
    entry.description,
    "",
    ...(entry.subcommands.length > 0
      ? [
          "| Subcommand | Description | Options |",
          "| --- | --- | --- |",
          ...entry.subcommands.map((subcommand) => {
            const route = subcommand.group
              ? `/${entry.name} ${subcommand.group} ${subcommand.name}`
              : `/${entry.name} ${subcommand.name}`;
            const options = subcommand.options.map((option) => `\`${option.name}\``).join(", ");
            return `| \`${route}\` | ${subcommand.description.replace(/\|/g, "\\|")} | ${options || "—"} |`;
          }),
          "",
        ]
      : ["No subcommands; the root has its own options.", ""]),
  ]),
  "## How to change this page",
  "",
  "1. Edit the command definition or manifest.",
  "2. Run `pnpm commands:catalog`.",
  "3. Run `pnpm check`.",
  "",
].join("\n");

const machinePath = path.join(root, "memory/machine/commands.json");
const vaultPath = path.join(root, "memory/vault/01-Mission/Command-Catalog.md");
await mkdir(path.dirname(machinePath), { recursive: true });
await mkdir(path.dirname(vaultPath), { recursive: true });
await writeFile(machinePath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
await writeFile(vaultPath, markdown, "utf8");

console.log(
  `commands: ${report.commands} roots, ${report.subcommands} subcommands, ${report.actions} actions`,
);
console.log(`wrote ${path.relative(root, machinePath)} and ${path.relative(root, vaultPath)}`);
